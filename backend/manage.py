"""Setup and admin utilities.

  python manage.py init                        create .env with fresh secrets + camera key
  python manage.py gen-cert --ip 192.168.1.100 self-signed TLS certificate for HTTPS
  python manage.py create-user NAME --role admin|security
  python manage.py verify-all                  check every incident against the blockchain
"""
import argparse
import datetime
import getpass
import ipaddress
import secrets
import socket
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ENV = BASE / ".env"


def cmd_init(args):
    from crypto_store import generate_key_b64

    if ENV.exists() and not args.force:
        sys.exit(".env already exists (use --force to overwrite - this makes old evidence unreadable!)")
    cam_key = secrets.token_urlsafe(24)
    ENV.write_text(f"""# Generated by manage.py init - keep this file private.
FLASK_SECRET_KEY={secrets.token_urlsafe(48)}
# AES-256 key for evidence. Back it up separately: losing it makes evidence unreadable.
EVIDENCE_KEY={generate_key_b64()}
CAMERA_KEYS=cam-01:{cam_key}

HOST=0.0.0.0
PORT=5000
YOLO_MODEL=yolo11n.pt
CONFIDENCE=0.45
ALERT_COOLDOWN_S=30

# ntfy: pick a long, unguessable topic and subscribe to it in the ntfy app.
NTFY_SERVER=https://ntfy.sh
NTFY_TOPIC=intrusion-{secrets.token_hex(8)}
NTFY_TOKEN=
DASHBOARD_URL=https://{guess_lan_ip()}:5000

ETH_RPC_URL=http://127.0.0.1:8545
ETH_PRIVATE_KEY=
""")
    print(f"Wrote {ENV}")
    print(f"Camera cam-01 API key (put in firmware secrets.h DEVICE_API_KEY):\n  {cam_key}")


def guess_lan_ip():
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("10.255.255.255", 1))
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def cmd_gen_cert(args):
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import NameOID

    ip = args.ip or guess_lan_ip()
    out = BASE / "certs"
    out.mkdir(exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, ip),
                      x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Intrusion Detection")])
    san = [x509.IPAddress(ipaddress.ip_address(ip)), x509.IPAddress(ipaddress.ip_address("127.0.0.1")),
           x509.DNSName("localhost")]
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder()
            .subject_name(name).issuer_name(name)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(minutes=5))
            .not_valid_after(now + datetime.timedelta(days=825))
            .add_extension(x509.SubjectAlternativeName(san), critical=False)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    (out / "server.key").write_bytes(key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    pem = cert.public_bytes(serialization.Encoding.PEM)
    (out / "server.crt").write_bytes(pem)
    print(f"Wrote {out / 'server.crt'} and server.key for IP {ip}")
    print("Paste this into SERVER_CA_CERT in firmware secrets.h:\n")
    print(pem.decode())


def cmd_create_user(args):
    from werkzeug.security import generate_password_hash
    from config import Config
    from db import Database

    db = Database(Config.DB_PATH)
    if db.get_user(args.username):
        sys.exit(f"user {args.username} already exists")
    pw = args.password or getpass.getpass("Password (min 10 chars): ")
    if len(pw) < 10:
        sys.exit("password too short")
    if not args.password and getpass.getpass("Repeat: ") != pw:
        sys.exit("passwords do not match")
    db.add_user(args.username, generate_password_hash(pw), args.role)
    print(f"created {args.role} user {args.username}")


def cmd_verify_all(args):
    from app import create_app
    ext = create_app(start_worker=False).extensions["intrusion"]
    bad = 0
    for inc in ext["db"].list_incidents(10000):
        rep = ext["verify"](inc)
        print(f"{inc['id']}  {rep['status']:<18} {rep['message']}")
        bad += not rep["verified"]
    print(f"\n{bad} incident(s) not verified")


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("init"); s.add_argument("--force", action="store_true"); s.set_defaults(fn=cmd_init)
    s = sub.add_parser("gen-cert"); s.add_argument("--ip"); s.set_defaults(fn=cmd_gen_cert)
    s = sub.add_parser("create-user"); s.add_argument("username")
    s.add_argument("--role", choices=["admin", "security"], default="security")
    s.add_argument("--password", help="omit to be prompted"); s.set_defaults(fn=cmd_create_user)
    s = sub.add_parser("verify-all"); s.set_defaults(fn=cmd_verify_all)
    args = p.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
